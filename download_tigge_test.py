"""
TEST ONLY: three small requests to the TIGGE archive, to see whether it can give us
day-ahead weather forecasts further back than March 2024.

It answers three questions before we build the real download:
  A. Does a day in 2021 download, and how long does one request take?
  B. Can one request hold several days? (If yes, the full download needs far fewer requests.)
  C. Does a recent day (October 2026) download too?

Before running
  1. pip install cdsapi
  2. Save your ECMWF Data Store key on your computer as the site's user guide explains.
     Keep the key out of this folder and out of GitHub.
  3. On the TIGGE page of the ECMWF Data Store, accept the TIGGE licence while logged in.

Run:   python download_tigge_test.py
It writes up to three small files named tigge_test_A.grib, tigge_test_B.grib, tigge_test_C.grib
and prints how long each request took. Each request waits in a queue, so it can take a while.

Source: TIGGE archive, ECMWF Data Store, https://ecds.ecmwf.int/datasets/tigge-forecasts
"""
import time
from pathlib import Path

import cdsapi

DATASET = "tigge-forecasts"

BASE = {    # copied from the request code generated by the TIGGE download form
    "origin": "ecmwf",
    "time": "00:00",                               # the run started at midnight UTC
    "level_type": "single_level",
    "variable": [
        "10_m_u_component_of_wind",
        "10_m_v_component_of_wind",
        "2_m_dewpoint_temperature",
        "2_m_temperature",
        "convective_available_potential_energy",
        "convective_inhibition",
        "maximum_2_m_temperature_in_the_last_6_hours",
        "mean_sea_level_pressure",
        "minimum_2_m_temperature_in_the_last_6_hours",
        "skin_temperature",
        "sunshine_duration",
        "surface_pressure",
        "total_cloud_cover",
        "total_column_water",
        "surface_latent_heat_flux",
        "surface_net_solar_radiation",
        "surface_net_thermal_radiation",
        "surface_sensible_heat_flux",
        "top_net_thermal_radiation",
        "total_precipitation",
    ],
    "forecast_type": "high_resolution_forecast",
    "leadtime_hour": ["18", "24", "30", "36", "42", "48"],   # hours after the start of the run
    "data_format": "grib",
    "area": [52, 2, 49, 7],                        # north, west, south, east: a box around Belgium
}

TESTS = {
    "A": {"year": "2021", "month": "01", "day": "01"},                  # one day at the start of our period
    "B": {"year": "2021", "month": "06", "day": ["01", "02", "03"]},    # three days in one request
    "C": {"year": "2026", "month": "10", "day": "20"},                  # one recent day
}


def main():
    client = cdsapi.Client()
    for name, when in TESTS.items():
        target = Path(f"tigge_test_{name}.grib")
        print(f"\n--- Test {name}: {when} ---", flush=True)
        start = time.time()
        try:
            client.retrieve(DATASET, {**BASE, **when}, str(target))
            print(f"Test {name}: OK in {time.time() - start:.0f} seconds, {target.stat().st_size / 1000:.0f} KB saved as {target}")
        except Exception as e:                     # keep going, so one failure does not hide the other answers
            print(f"Test {name}: FAILED after {time.time() - start:.0f} seconds")
            print(f"  {type(e).__name__}: {e}")
    print("\nDone. Copy everything printed above and send it back.")


if __name__ == "__main__":
    main()
